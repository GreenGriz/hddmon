def critical_help(protocol: str | None, th: Thresholds | None = None) -> list[ParamHelp]:
    """Описания критичных параметров для протокола ata/scsi/nvme."""
    thresholds = th or Thresholds()
    if protocol == "scsi":
        return _scsi(thresholds)
    if protocol == "nvme":
        return _nvme(thresholds)
    return _ata(thresholds)
