        shows="PASSED или FAILED. Это не «здоров ли диск вообще», а сработал ли хоть один критический внутренний порог.",
        why="FAILED — самое сильное предупреждение, которое диск может дать сам. Ждать, пока он перестанет читаться, уже поздно.",
        worry="FAILED → в hddmon это REPLACE_NOW. Немедленный бэкап и замена; дальше диск может отказать в любой момент.",
