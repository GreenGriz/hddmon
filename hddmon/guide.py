"""Справочник по критичным SMART-параметрам для `hddmon smart --explain`."""

from __future__ import annotations

from dataclasses import dataclass

from .config import Thresholds


@dataclass(frozen=True)
class ParamHelp:
    key: str
    title: str
    what: str
    shows: str
